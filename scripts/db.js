#!/usr/bin/env node
// Database CLI.   node scripts/db.js <command>
//   init                 create tables (idempotent) and record the migration
//   seed                 load the sample township into an EMPTY database
//   reset                wipe every table and reload the sample township (destructive)
//   import-json <file>   import a legacy JSON snapshot into an EMPTY database
//   export-json <file>   write the current database as JSON (backup / hand-over)
//   seed-sql <file>      write the sample township as a plain .sql INSERT script (database/seed.sql)
import '../server/env.js'; // must be first: loads .env into process.env
import fs from 'node:fs';
import { openDatabase, applySchema } from '../server/db/index.js';
import { initDatabase, resetDemo, importJsonSnapshot, userCount } from '../server/db/bootstrap.js';
import { importLegacy, recordingExecutor } from '../server/db/import.js';
import { seedDatabase } from '../server/seed.js';
import { createRepos } from '../server/repos/index.js';
import { dbConfigFromEnv, safeDescribe, explainDbError } from '../server/db/config.js';

const [cmd, arg] = process.argv.slice(2);
if (!cmd) { console.error('Usage: node scripts/db.js <init|seed|reset|import-json FILE|export-json FILE|seed-sql FILE>'); process.exit(2); }

if (cmd === 'seed-sql') {
  // Needs no database connection: it only renders the importer's INSERTs as text.
  const rec = recordingExecutor();
  const fixed = new Date('2026-11-03T10:00:00Z');
  await importLegacy(rec, seedDatabase(fixed), { importedAt: fixed.toISOString() });
  const head = `-- NESTORA sample township (generated by "node scripts/db.js seed-sql"). Run after database/schema.sql.\n-- Dates are anchored to ${fixed.toISOString().slice(0, 10)}; prefer "npm run db:seed" for dates relative to today.\nSET NAMES utf8mb4;\nSTART TRANSACTION;\n`;
  fs.writeFileSync(arg || 'database/seed.sql', `${head}${rec.lines.join('\n')}\nCOMMIT;\n`);
  console.log(`wrote ${arg || 'database/seed.sql'} (${rec.lines.length} statements)`);
  process.exit(0);
}

let db;
try { db = await openDatabase({ engine: process.env.DB_ENGINE }); }
catch (e) { console.error(`Cannot start: ${explainDbError(e)}`); process.exit(1); }
try {
  console.log(`Using ${db.engine}${db.engine === 'mysql' ? ' ' + safeDescribe(dbConfigFromEnv()) : ''}`);
  if (cmd === 'init') { await applySchema(db); console.log('Schema is up to date.'); }
  else if (cmd === 'seed') { await applySchema(db); if (await userCount(db)) throw new Error('Database already has data. Use "reset" to replace it.'); await initDatabase(db); console.log('Sample township loaded.'); }
  else if (cmd === 'reset') { await applySchema(db); await resetDemo(db); console.log('Database wiped and sample township reloaded.'); }
  else if (cmd === 'import-json') { const r = await importJsonSnapshot(db, JSON.parse(fs.readFileSync(arg, 'utf8'))); console.log('Imported:', r); }
  else if (cmd === 'export-json') {
    const r = createRepos(db);
    const snapshot = { exportedAt: new Date().toISOString(), config: await r.core.getConfig(), flats: await r.core.flats(), staff: await r.core.staffList(), bills: await r.billing.allBills(), ledger: await r.billing.allLedger(), complaints: await r.complaints.list(), bankTxns: await r.bank.txns(), notices: await r.community.notices(), amenities: await r.community.amenities() };
    fs.writeFileSync(arg, JSON.stringify(snapshot, null, 1));
    console.log(`Exported to ${arg}`);
  } else { console.error(`Unknown command: ${cmd}`); process.exitCode = 2; }
} catch (e) { console.error(explainDbError(e, db.engine === 'mysql' ? dbConfigFromEnv() : null)); process.exitCode = 1; } finally { await db.close().catch(() => {}); }
